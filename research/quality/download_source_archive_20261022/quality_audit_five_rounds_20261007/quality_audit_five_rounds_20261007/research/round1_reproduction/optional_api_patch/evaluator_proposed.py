"""Minimal public quality API. Geometry measurement != semantic truth.
No target, applicability or detail label is inferred from GT score or point count.
"""
from __future__ import annotations
import math
from shapely.geometry import Polygon, shape
from components import intrinsic,compare
from quality import region_metrics

def evaluate(layout:dict,references:list[dict],context:dict|None=None,centroid_weight:float|None=None)->dict:
 """Evaluate one complete annotation or footprint-only output.
 context can supply target_compatibility, reference_usable, manhattan_applicability,
 flat_top_applicability and requirements [{id, necessity, status, source}].
 Status values are caller evidence, never generated by this numeric evaluator.
 """
 context=context or {}
 if centroid_weight is not None and (not math.isfinite(centroid_weight) or centroid_weight<0):
  raise ValueError('centroid_weight must be finite and nonnegative')
 complete=layout.get('points') is not None
 requirements=context.get('requirements',[])
 for q in requirements:
  if q.get('status') in {'met','violated'} and not q.get('source'):
   raise ValueError('claimed requirement judgments need a source')
 conflicts=[q['id'] for q in requirements if q.get('necessity')=='required' and q.get('status')=='violated']
 intrinsic_values=intrinsic(layout) if complete else {'geometry_status':'footprint_only','top_and_3d':'not_applicable_no_upper_output'}
 results=[]
 for g in references:
  if complete:row=compare(layout,g)
  else:
   from components import footprint
   p=shape(layout['geometry']) if 'geometry' in layout else Polygon(layout['footprint'])
   if not p.is_valid or p.is_empty:raise ValueError('invalid footprint; no automatic repair')
   _,pg=footprint(g)
   row={'reference_id':g.get('id'),'reference_version':g.get('version'),'reference_status':'ok',**region_metrics(p,pg),'longitude_status':'not_applicable_no_upper_output','conditional_3d_status':'not_applicable_no_upper_output'}
  if centroid_weight is not None and row.get('iou') is not None:
   row['spatial_reference_cost']=(1-row['iou'])+centroid_weight*row['centroid_distance_normalized']
   row['centroid_weight']=centroid_weight
   row['cost_meaning']='reference proximity with specified translation cost, NOT overall quality'
  results.append(row)
 target=context.get('target_compatibility','unknown')
 # The supplied context is still global caller evidence, not a per-reference judgment.
 context_ready=target=='confirmed_same_target' and context.get('reference_usable') is True and not conflicts
 for row in results:
  range_computed=(row.get('reference_status')=='ok' and all(
   isinstance(row.get(key),(int,float)) and math.isfinite(row[key])
   for key in ('iou','centroid_distance_normalized')))
  row['spatial_reference_cost_comparable_with_same_context']=bool(context_ready and range_computed)
 # A global true flag means every supplied reference has a computable spatial comparison.
 # Angular/3-D availability and overall quality remain separate.
 rank_ready=bool(results) and all(row['spatial_reference_cost_comparable_with_same_context'] for row in results)
 return {'id':layout.get('id'),'expression':{'pair_count':len(layout['points'])//2 if complete else None,'connectivity':'supplied_cyclic_order_unchanged' if complete else 'supplied_region','different_pair_counts_remain_different_expressions':True,'same_count_does_not_assert_same_expression':True},
  'reference_agreement':results,'intrinsic_conditional_geometry':intrinsic_values,
  'applicability':{'manhattan':context.get('manhattan_applicability','unknown'),'flat_top':context.get('flat_top_applicability','unknown')},
  'target_compatibility':target,'requirements':requirements,'known_required_conflicts':conflicts,
  'reference_cost_comparable_with_same_context':rank_ready,
  'overall_quality_score':None,'overall_state':'known_requirement_conflict' if conflicts else 'accepted_target_difference_not_automatic_error' if target=='accepted_alternative_target' else 'numeric_reference_comparison_only' if not rank_ready else 'comparable_reference_components; intrinsic and detail remain separately visible',
  'input_eligibility_unchanged':True}
