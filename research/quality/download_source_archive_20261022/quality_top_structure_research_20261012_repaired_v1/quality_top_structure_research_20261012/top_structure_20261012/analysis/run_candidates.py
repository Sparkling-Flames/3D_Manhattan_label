#!/usr/bin/env python3
"""Apply predeclared functions to audited real and controlled components."""
from __future__ import annotations
import argparse,csv,hashlib,json,sys
from pathlib import Path
from candidate_functions import score,PRIMARY_METHODS,DIAGNOSTIC_METHODS

def readcsv(p):
    with p.open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
def dump(p,x):p.write_text(json.dumps(x,ensure_ascii=False,indent=2,allow_nan=False)+'\n')
def csvwrite(p,rows):
    fields=list(dict.fromkeys(k for x in rows for k in x))
    with p.open('w',encoding='utf-8',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(rows)
def sh(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--root',type=Path,default=Path.cwd());a=ap.parse_args();r=a.root.resolve();p=r/'top_structure_20261012';o=p/'analysis/results';o.mkdir(parents=True,exist_ok=True)
    inputs=[r/'study_quality/results/candidate_scores.json',p/'mechanisms/results/real_39_centered_components.csv',p/'representation/results/representation_signals_all3152.csv',p/'representation/results/raw_boundary_cases.csv']
    old=json.loads(inputs[0].read_text());cent={x['record_id']:x for x in readcsv(inputs[1])};xr={x['record_id']:x for x in readcsv(inputs[2])};raw={x['record_id']:x for x in readcsv(inputs[3])};rows=[]
    allowed=json.loads((p/'evidence/results/numeric_evidence_39_metadata.json').read_text())
    assert {x['record_id'] for x in old}=={x['record_id'] for x in allowed}
    assert len({x['record_id'] for x in allowed})==39
    # Qualification is independently regenerated by evidence/audit_qualification.py.
    for x in old:
        x=dict(x);rid=x['record_id'];z=xr[rid]
        assert str(z['held_out']).lower()=='false'
        x['Hcenter']=float(cent[rid]['Hcenter'])
        x['X_rms_deg']=float(z['X_pair_rms_deg']) if z['pair_mechanically_valid']=='True' and z['source_midpoint_verified']=='True' and z['X_pair_rms_deg'] else None
        x['X_max_deg']=float(z['X_pair_max_deg']) if x['X_rms_deg'] is not None else None
        x['pairing_basis']=z['pairing_basis'];x['ring_confirmed']=z['ring_confirmed'];x['current_before_changed_from_export']=z['current_before_changed_from_export']
        for k in ['S_top_raw_deg','S_bottom_raw_deg']:
            x[k]=float(raw[rid][k]) if raw.get(rid,{}).get(k) else None
        new=score(x)
        for k in ['Q_v11','Q_floor_iou','Q_official_iou3d','Q_no_topS','Q_IHC_h050','Q_quarter_topS','Q_rawS_same_parameters']:
            if new[k] is not None:assert abs(new[k]-float(x[k]))<1e-9,(rid,k)
        x.update(new);rows.append(x)
    assert len(rows)==39
    csvwrite(o/'candidate_scores_39.csv',rows);dump(o/'candidate_scores_39.json',rows)
    ss=readcsv(p/'mechanisms/results/synthetic_components.csv');cs={x['case_id']:x for x in readcsv(p/'mechanisms/results/synthetic_centered_components.csv')};synt=[]
    for x in ss:
        x=dict(x)
        if x['status']=='available':x['Hcenter']=float(cs[x['case_id']]['Hcenter']);x.update(score(x))
        synt.append(x)
    csvwrite(o/'candidate_scores_synthetic.csv',synt)
    xrows=[]
    for x in readcsv(p/'representation/results/controlled_x_results.csv'):
        x=dict(x)
        if x['status']=='available':
            x['S_top_raw_deg']=x['raw_S_top_deg'];x['S_bottom_raw_deg']=x['raw_S_bottom_deg'];x.update(score(x))
        xrows.append(x)
    csvwrite(o/'candidate_scores_x_controls.csv',xrows)
    dump(o/'run_manifest.json',{'records':39,'old24':24,'new_severe':9,'new_borderline':6,'unreviewed_labels_used':0,'heldout_rows_used':0,'main_sha':'38e259c043fed0817307dbc3d21c6dba06bd6662','protocol_sha256':sh(p/'analysis/protocol_before_candidate_results.json'),'structural_addendum_sha256':sh(p/'analysis/protocol_structural_addendum_before_results.json'),'qualification_subset_sha256':sh(p/'evidence/results/numeric_evidence_39_metadata.json'),'code_sha256':sh(Path(__file__)),'scalar_function_sha256':sh(p/'analysis/candidate_functions.py'),'input_hashes':{str(q.relative_to(r)):sh(q) for q in inputs},'synthetic_rows':len(synt),'primary_methods':PRIMARY_METHODS,'diagnostic_methods':DIAGNOSTIC_METHODS,'parameters_fitted':False,'source_points_changed':False})
    print(json.dumps({'rows':len(rows),'T20':next(x for x in rows if x['old_case_id']=='T20'),'synthetic_rows':len(synt)},ensure_ascii=False))
if __name__=='__main__':main()
