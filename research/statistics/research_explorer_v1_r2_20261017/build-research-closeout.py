"""Regenerate offline data from the checked-in archive. No network or research recomputation."""
from pathlib import Path
import csv, hashlib, json
here = Path(__file__).resolve().parent
root = here.parents[2]
paths = {
    'personnel': 'research/workers/personnel_effective_exchange_conditions_20261022/audit/PERSONNEL_UNIFIED_RESULT_ZH.csv',
    'members': 'research/workers/personnel_effective_exchange_conditions_20261022/audit/PERSONNEL_TARGET_CLASS_MEMBERS_ZH.csv',
    'sameRoom': 'research/same_room/same_room_acceptance_20261022/SAME_ROOM_ACCEPTANCE.csv',
}
data = {'schemaVersion': 1, 'snapshot': '2026-10-21', 'sourceFiles': {}}
for key, path in paths.items():
    source = root / path
    with source.open(encoding='utf-8-sig', newline='') as stream:
        data[key] = list(csv.DictReader(stream))
    data['sourceFiles'][key] = {'path':path, 'sha256':hashlib.sha256(source.read_bytes()).hexdigest(), 'rows':len(data[key])}
(here / 'research-closeout-data.js').write_text('/* Generated by build-research-closeout.py; evidence snapshot, not research recomputation. */\nwindow.RESEARCH_CLOSEOUT_DATA = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n', encoding='utf-8')
